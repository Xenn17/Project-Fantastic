create table if not exists public.applications (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  name text not null, ign text not null, age integer not null, gender text not null,
  role text not null, secondary_role text not null, highest_rank text not null,
  current_rank text not null, main_hero text not null, hero_win_rate text not null,
  other_heroes text not null, ml_id text not null, whatsapp text not null,
  discord text not null, screenshots text
);
alter table public.applications enable row level security;
drop policy if exists "Allow public application inserts" on public.applications;
create policy "Allow public application inserts" on public.applications
for insert to anon with check (true);
drop policy if exists "Allow admin panel reads" on public.applications;
create policy "Allow admin panel reads" on public.applications
for select to anon using (true);
drop policy if exists "Allow admin panel deletes" on public.applications;
create policy "Allow admin panel deletes" on public.applications
for delete to anon using (true);


-- Screenshot storage for join applications
insert into storage.buckets (id, name, public)
values ('application-screenshots', 'application-screenshots', true)
on conflict (id) do update set public = true;
drop policy if exists "Allow application screenshot uploads" on storage.objects;
create policy "Allow application screenshot uploads" on storage.objects
for insert to anon with check (bucket_id = 'application-screenshots');
drop policy if exists "Allow public application screenshot reads" on storage.objects;
create policy "Allow public application screenshot reads" on storage.objects
for select to anon using (bucket_id = 'application-screenshots');

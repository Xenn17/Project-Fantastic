-- F4NTASTIC gallery base schema.
-- Run once in the SQL Editor of the project used by js/gallery-supabase-config.js.

create table if not exists public.gallery_categories (
  id uuid primary key default gen_random_uuid(),
  name text not null unique,
  description text not null default '',
  tag text not null default 'NEW COLLECTION',
  slug text,
  created_at timestamptz not null default now()
);

create table if not exists public.gallery_photos (
  id uuid primary key default gen_random_uuid(),
  category_id uuid not null references public.gallery_categories(id) on delete restrict,
  label text not null default '',
  title text not null,
  description text not null default '',
  image_path text not null,
  media_type text not null default 'image',
  sort_order integer not null default 0,
  is_published boolean not null default false,
  created_by uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.gallery_managers (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null,
  role text not null check (role in ('admin', 'developer')),
  created_at timestamptz not null default now()
);

create table if not exists public.gallery_activity_logs (
  id bigint generated by default as identity primary key,
  actor_id uuid not null references auth.users(id) on delete cascade,
  action text not null,
  target_id uuid,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists gallery_photos_category_order_idx
  on public.gallery_photos(category_id, sort_order, created_at desc);

create or replace function public.is_gallery_manager()
returns boolean language sql stable security definer set search_path = public
as $$ select exists (select 1 from public.gallery_managers where id = auth.uid()); $$;

create or replace function public.is_gallery_developer()
returns boolean language sql stable security definer set search_path = public
as $$ select exists (select 1 from public.gallery_managers where id = auth.uid() and role = 'developer'); $$;

create or replace function public.get_gallery_role()
returns text language sql stable security definer set search_path = public
as $$ select role from public.gallery_managers where id = auth.uid() limit 1; $$;

grant execute on function public.is_gallery_manager() to anon, authenticated;
grant execute on function public.is_gallery_developer() to authenticated;
grant execute on function public.get_gallery_role() to authenticated;

grant select on public.gallery_categories, public.gallery_photos to anon, authenticated;
grant insert, update, delete on public.gallery_categories, public.gallery_photos to authenticated;
grant select, insert, update, delete on public.gallery_managers, public.gallery_activity_logs to authenticated;

alter table public.gallery_categories enable row level security;
alter table public.gallery_photos enable row level security;
alter table public.gallery_managers enable row level security;
alter table public.gallery_activity_logs enable row level security;

drop policy if exists "Anyone can view gallery categories" on public.gallery_categories;
create policy "Anyone can view gallery categories" on public.gallery_categories
  for select to anon, authenticated using (true);
drop policy if exists "Managers manage gallery categories" on public.gallery_categories;
create policy "Managers manage gallery categories" on public.gallery_categories
  for all to authenticated using (public.is_gallery_manager()) with check (public.is_gallery_manager());

drop policy if exists "Anyone can view published gallery photos" on public.gallery_photos;
create policy "Anyone can view published gallery photos" on public.gallery_photos
  for select to anon, authenticated using (is_published or public.is_gallery_manager());
drop policy if exists "Managers manage gallery photos" on public.gallery_photos;
create policy "Managers manage gallery photos" on public.gallery_photos
  for all to authenticated using (public.is_gallery_manager()) with check (public.is_gallery_manager());

drop policy if exists "Managers can view manager list" on public.gallery_managers;
create policy "Managers can view manager list" on public.gallery_managers
  for select to authenticated using (public.is_gallery_manager());
drop policy if exists "Developers manage admin accounts" on public.gallery_managers;
create policy "Developers manage admin accounts" on public.gallery_managers
  for all to authenticated using (public.is_gallery_developer() and role = 'admin')
  with check (public.is_gallery_developer() and role = 'admin');

drop policy if exists "Managers can view activity logs" on public.gallery_activity_logs;
create policy "Managers can view activity logs" on public.gallery_activity_logs
  for select to authenticated using (public.is_gallery_manager());
drop policy if exists "Managers can insert own activity logs" on public.gallery_activity_logs;
create policy "Managers can insert own activity logs" on public.gallery_activity_logs
  for insert to authenticated
  with check (actor_id = auth.uid() and public.is_gallery_manager());


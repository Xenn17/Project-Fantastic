create table if not exists public.reports (
  id bigint generated by default as identity primary key,
  reporter_id uuid not null references auth.users(id) on delete cascade,
  target_player text not null,
  target_contact text,
  category text not null check (category in ('bullying','scam','toxic','agreement','internal','rw','dk','other')),
  incident_date date,
  description text not null,
  evidence_paths text[] not null default '{}',
  status text not null default 'new' check (status in ('new','in_review','need_info','resolved','dismissed')),
  admin_note text,
  assigned_to uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  resolved_at timestamptz
);

alter table public.reports drop constraint if exists reports_category_check;
alter table public.reports add constraint reports_category_check check (category in ('bullying','scam','toxic','agreement','internal','rw','dk','other'));

-- Tautkan player yang dilaporkan ke profil member (kosong jika player di luar daftar).
alter table public.reports add column if not exists target_member_id uuid references public.profiles(id) on delete set null;

-- Hubungkan laporan ke profil agar admin dapat melihat username pelapor.
alter table public.reports drop constraint if exists reports_reporter_profile_fkey;
alter table public.reports add constraint reports_reporter_profile_fkey foreign key (reporter_id) references public.profiles(id) on delete cascade;

-- Helper staff: SECURITY DEFINER mencegah policy profiles melakukan query rekursif ke profiles.
create or replace function public.f4_is_staff()
returns boolean
language sql
security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role in ('admin','developer')
  );
$$;
revoke all on function public.f4_is_staff() from public;
grant execute on function public.f4_is_staff() to authenticated;

-- Hapus policy lama yang menyebabkan infinite recursion, lalu pakai helper aman.
drop policy if exists "Admins can read profiles" on public.profiles;
create policy "Admins can read profiles" on public.profiles
for select to authenticated
using (auth.uid() = id or public.f4_is_staff());

alter table public.reports enable row level security;
revoke all on public.reports from anon;
grant select, insert on public.reports to authenticated;
grant update, delete on public.reports to authenticated;

drop policy if exists "Admins delete reports" on public.reports;
create policy "Admins delete reports" on public.reports
for delete to authenticated
using (public.f4_is_staff());

drop policy if exists "Members create own reports" on public.reports;
create policy "Members create own reports" on public.reports
for insert to authenticated
with check (
  reporter_id = auth.uid()
  and exists (select 1 from public.profiles p where p.id = auth.uid() and p.role in ('member','admin','developer'))
);

drop policy if exists "Members read own reports" on public.reports;
create policy "Members read own reports" on public.reports
for select to authenticated
using (
  reporter_id = auth.uid()
  or exists (select 1 from public.profiles p where p.id = auth.uid() and p.role in ('admin','developer'))
);

-- Jika role developer proyek ini disimpan di gallery_managers, perluas policy yang sama.
do $$
begin
  if to_regclass('public.gallery_managers') is not null then
    drop policy if exists "Members read own reports" on public.reports;
    create policy "Members read own reports" on public.reports
    for select to authenticated
    using (
      reporter_id = auth.uid()
      or exists (select 1 from public.profiles p where p.id = auth.uid() and p.role in ('admin','developer'))
      or exists (select 1 from public.gallery_managers m where m.id = auth.uid() and m.role = 'developer')
    );
  end if;
end $$;

drop policy if exists "Admins manage reports" on public.reports;
create policy "Admins manage reports" on public.reports
for update to authenticated
using (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role in ('admin','developer')))
with check (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role in ('admin','developer')));

drop policy if exists "Members update own report text" on public.reports;
create policy "Members update own report text" on public.reports
for update to authenticated
using (reporter_id = auth.uid() and status = 'need_info')
with check (reporter_id = auth.uid() and status = 'need_info');

create or replace function public.f4_touch_report_updated_at()
returns trigger language plpgsql security definer set search_path = public, pg_temp as $$
begin
  new.updated_at := now();
  if new.status in ('resolved','dismissed') and old.status not in ('resolved','dismissed') then new.resolved_at := now(); end if;
  return new;
end;
$$;
drop trigger if exists f4_reports_updated_at on public.reports;
create trigger f4_reports_updated_at before update on public.reports for each row execute function public.f4_touch_report_updated_at();

